const {
  withAppDelegate,
  withDangerousMod,
  withXcodeProject,
} = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const marker = "// @generated by with-document-scanner";
const requiredImports = [
  "import Vision",
  "import VisionKit",
  "import CoreImage",
  "import PDFKit",
  "import QuickLook",
];

module.exports = function withDocumentScanner(config) {
  config = withDangerousMod(config, ["ios", (iosConfig) => {
    const projectName = iosConfig.modRequest.projectName;
    const destination = path.join(
      iosConfig.modRequest.platformProjectRoot,
      "DocumentScannerBridge.m"
    );
    fs.copyFileSync(path.join(__dirname, "DocumentScannerBridge.m"), destination);
    return iosConfig;
  }]);

  config = withXcodeProject(config, (iosConfig) => {
    const project = iosConfig.modResults;
    const projectName = iosConfig.modRequest.projectName;
    const filePath = "DocumentScannerBridge.m";
    if (!project.hasFile(filePath)) {
      const groupKey = project.findPBXGroupKey({ name: projectName });
      project.addSourceFile(
        filePath,
        { target: project.getFirstTarget().uuid },
        groupKey
      );
    }
    return iosConfig;
  });

  config = withAppDelegate(config, (appConfig) => {
    if (appConfig.modResults.language !== "swift") {
      throw new Error("MediVault document scanning requires a Swift AppDelegate.");
    }

    let source = appConfig.modResults.contents;
    for (const requiredImport of requiredImports) {
      if (!source.includes(requiredImport)) {
        const lastImport = [...source.matchAll(/^import .+$/gm)].at(-1);
        const insertionPoint = lastImport.index + lastImport[0].length;
        source = `${source.slice(0, insertionPoint)}\n${requiredImport}${source.slice(insertionPoint)}`;
      }
    }

    if (!source.includes("class DocumentScanner:")) {
      const moduleSource = fs.readFileSync(
        path.join(__dirname, "DocumentScanner.swift"),
        "utf8"
      );
      source = `${source.trimEnd()}\n\n${marker}\n${moduleSource.trim()}\n`;
    }
    appConfig.modResults.contents = source;
    return appConfig;
  });

  return config;
};
